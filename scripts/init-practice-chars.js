exports.main = async (event, context) => {
  const db = cloud.database()
  const collection = db.collection('course_lessons')

  const results = []
  for (const [lessonNo, practiceChars] of Object.entries(PRACTICE_CHARS)) {
    try {
      const res = await collection.where({ lessonNo: parseInt(lessonNo) }).update({
        data: { practiceChars: practiceChars }
      })
      results.push({ lessonNo: parseInt(lessonNo), updated: res.stats.updated })
    } catch (err) {
      results.push({ lessonNo: parseInt(lessonNo), error: err.message })
    }
  }

  return { code: 0, data: results }
}
